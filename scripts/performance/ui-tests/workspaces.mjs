import assert from 'node:assert/strict'
import { facility, id } from '../ui-data.mjs'

export async function workspaces(h) {
  const { page, context, data } = await h.page('OWNER')
  const mediaUrl = h.base + '/api/v1/media/private-ui-fixture'
  data.media = [{ id: id(350), url: mediaUrl, fileName: 'uploaded.png' }]
  await page.route('**/api/v1/media/private-ui-fixture', route => route.fulfill({ status: 302, headers: { location: h.base + '/placeholder-user.jpg?signature=synthetic' } }))
  await page.goto(h.base + `/owner/facilities/${facility.id}`)
  await page.getByRole('heading', { name: /Thông tin liên hệ & Giới thiệu/ }).waitFor()
  await page.waitForLoadState('networkidle')
  for (const path of [`/owner/facilities/${facility.id}`, `/owner/facilities/${facility.id}/courts`, `/owner/facilities/${facility.id}/images`]) {
    assert.equal(data.calls.filter(call => call.path === path && call.method === 'GET').length, 1, path)
  }
  const uploaded = page.getByRole('img', { name: 'Ảnh cơ sở', exact: true })
  await uploaded.scrollIntoViewIfNeeded()
  await uploaded.evaluate(image => image.decode())
  assert.equal(await uploaded.getAttribute('src'), mediaUrl)
  assert.ok(await uploaded.evaluate(image => image.naturalWidth) > 0)
  h.pass('Uploaded/private gallery image retains its original authorized URL and signed redirect without the local WebP/optimizer path')
  await page.locator('aside').getByRole('button', { name: new RegExp(facility.name) }).click()
  await page.locator('aside').getByRole('link', { name: /Cơ sở thứ hai/ }).click()
  await page.waitForURL('**/owner/facilities/' + id(100))
  await page.getByRole('heading', { name: /Thông tin liên hệ & Giới thiệu/ }).waitFor()
  h.pass('Facility context is shared by overview/sidebar/breadcrumb; switcher changes facility without duplicate resource reads')

  await page.goto(h.base + `/owner/facilities/${facility.id}/staff`)
  const card = page.locator('div.rounded-2xl').filter({ has: page.getByRole('heading', { name: 'Nhân viên thử', exact: true }) }).last()
  await card.getByRole('button', { name: 'Lưu quyền hạn' }).waitFor()
  await card.getByRole('checkbox', { name: 'Hoàn tiền lượt đặt theo chính sách' }).uncheck()
  await Promise.all([page.waitForResponse(response => response.url().endsWith('/permissions') && response.request().method() === 'PUT'), card.getByRole('button', { name: 'Lưu quyền hạn' }).click()])
  const first = data.calls.find(call => call.method === 'PUT' && call.path.endsWith('/permissions')).body
  assert.equal(first.permissions.includes('BOOKING_REFUND'), false); assert.equal(first.permissions.includes('TRANSFER_PAYOUT'), true); assert.equal(first.expectedVersion, 7)
  await card.getByRole('checkbox', { name: 'Hoàn tiền lượt đặt theo chính sách' }).check()
  await card.getByRole('checkbox', { name: 'Trả tiền cho người chuyển nhượng' }).uncheck()
  await Promise.all([page.waitForResponse(response => response.url().endsWith('/permissions') && response.request().method() === 'PUT'), card.getByRole('button', { name: 'Lưu quyền hạn' }).click()])
  const second = data.calls.filter(call => call.method === 'PUT' && call.path.endsWith('/permissions')).at(-1).body
  assert.equal(second.permissions.includes('BOOKING_REFUND'), true); assert.equal(second.permissions.includes('TRANSFER_PAYOUT'), false)
  data.failPermission = true
  await card.getByRole('button', { name: 'Lưu quyền hạn' }).click()
  await card.getByRole('alert').filter({ hasText: 'Bạn không có quyền' }).waitFor()
  h.pass('Owner permission editor grants/revokes refund and seller payout independently; server 403 remains visible')

  await page.goto(h.base + `/owner/facilities/${facility.id}/reports`)
  await page.getByText('125.000 ₫', { exact: true }).first().waitFor()
  await page.locator('input[name=fromDate]').fill('2026-10-22')
  await page.locator('input[name=toDate]').fill('2026-10-23')
  await page.getByRole('button', { name: 'Xem báo cáo', exact: true }).click()
  await page.getByText(/27 dòng · Trang 1\/2/).waitFor()
  await page.getByRole('button', { name: 'Trang sau', exact: true }).click()
  await page.getByText(/27 dòng · Trang 2\/2/).waitFor()
  assert.ok(data.calls.some(call => call.path.includes('fromDate=2026-10-22&toDate=2026-10-23&page=1')))
  await page.getByText('125.000 ₫', { exact: true }).first().waitFor()
  data.reportAvailability = 'UNAVAILABLE'
  await page.getByRole('button', { name: 'Làm mới báo cáo', exact: true }).click()
  await page.getByText(/Chưa tải đủ dữ liệu tiền/).waitFor()
  assert.equal(await page.getByText('125.000 ₫', { exact: true }).count(), 0)
  h.pass('Report range and pagination remain linked; totals come from summary and UNAVAILABLE never becomes zero revenue')

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Mở hoặc thu gọn thanh bên' }).click()
  await page.locator('aside').getByRole('link', { name: 'Tổng quan cơ sở', exact: true }).click()
  await page.waitForURL('**/owner/facilities/' + facility.id)
  await page.locator('header').first().getByRole('button', { name: 'Mở menu di động' }).click()
  await page.locator('header').first().getByRole('link', { name: 'Tìm kiếm sân', exact: true }).click()
  await page.waitForURL('**/search')
  await page.getByRole('button', { name: 'Mở menu di động' }).waitFor()
  h.pass('Mobile facility sidebar and header menus navigate and close after URL changes')
  await context.close()

  const admin = await h.page('ADMIN')
  await admin.page.goto(h.base + '/admin/accounts')
  await admin.page.locator('input[name=q]').fill('nhân viên')
  await admin.page.locator('select[name=role]').selectOption('STAFF')
  await Promise.all([admin.page.waitForResponse(response => response.url().includes('/admin/accounts?')), admin.page.getByRole('button', { name: 'Tra cứu ngay' }).click()])
  assert.ok(admin.data.calls.some(call => call.path.includes('/admin/accounts?q=nh%C3%A2n+vi%C3%AAn&role=STAFF')))
  await admin.page.getByRole('button', { name: 'Đặt lại', exact: true }).click()
  await admin.page.goto(h.base + '/admin/accounts/' + id(390))
  await admin.page.getByRole('button', { name: 'Cập nhật vai trò', exact: true }).click()
  await admin.page.locator('input[name=roles][value=STAFF]').check()
  await admin.page.locator('input[name=reason]').fill('Kiểm chứng thay đổi vai trò')
  await Promise.all([admin.page.waitForResponse(response => response.url().endsWith('/roles') && response.request().method() === 'PUT'), admin.page.getByRole('button', { name: 'Xác nhận cập nhật', exact: true }).click()])
  assert.deepEqual(admin.data.calls.find(call => call.path.endsWith('/roles')).body, { roles: ['CUSTOMER', 'STAFF'], reason: 'Kiểm chứng thay đổi vai trò' })
  await admin.page.goto(h.base + '/admin/refunds/' + id(391))
  await admin.page.locator('textarea[name=note]').fill('Ghi chú kiểm chứng, không thực hiện hoàn tiền')
  await admin.page.getByRole('button', { name: 'Lưu ghi chú, không thực thi hoàn tiền', exact: true }).click()
  await admin.page.getByText('Ghi chú kiểm chứng, không thực hiện hoàn tiền', { exact: true }).waitFor()
  assert.equal(admin.data.calls.filter(call => call.path.includes('/demo-finance/') && call.method === 'POST').length, 0)
  await admin.context.close()
  h.pass('Admin shell/nav, account filters/roles and refund notes send the original contracts; a note never executes money')

  const staff = await h.page('STAFF')
  await staff.page.goto(h.base + `/owner/facilities/${facility.id}/staff`)
  await staff.page.getByText(/không có quyền|không được cấp quyền/i).first().waitFor()
  assert.equal(staff.data.calls.some(call => call.path.startsWith('/staff-profiles')), false)
  const missing = await staff.page.goto(h.base + '/staff/not-a-real-route')
  assert.equal(missing.status(), 404)
  await staff.page.getByText('404 · KHÔNG TÌM THẤY TRANG', { exact: true }).waitFor()
  await staff.context.close()
  h.pass('Invalid routes stay invalid and Staff cannot load the Owner permission editor')
}
