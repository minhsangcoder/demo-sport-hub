import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const directory = new URL('../features/facility/', import.meta.url)
const source = JSON.parse(
  readFileSync(new URL('vietnam-administrative-divisions.json', directory), 'utf8'),
)
const output = `// Generated by scripts/generate-provinces.mjs from the authoritative administrative JSON.\nexport const attribution = ${JSON.stringify(source.attribution)}\nexport const provinces: { code: string; name: string }[] = ${JSON.stringify(
  source.provinces.map(({ code, name }) => ({ code, name })),
  null,
  2,
)}\n`
const target = new URL('provinces.data.ts', directory)
if (process.argv.includes('--check')) {
  // Formatting is separate from the generated data identity.
  const actual = readFileSync(target, 'utf8')
  const names = source.provinces.map(({ code, name }) => ({ code, name }))
  const expected = JSON.stringify(names)
  const serialized = actual.slice(actual.indexOf('= [') + 2).trim()
  // The checked-in generator output intentionally remains ordinary JSON-compatible literals.
  if (JSON.stringify(JSON.parse(serialized)) !== expected) throw new Error('Province data is stale')
  console.log(`Verified ${names.length} province codes/names`)
} else {
  writeFileSync(target, output)
  console.log(fileURLToPath(target))
}
